/// One authored cable run: `count` links from `from` to `to`.
///
/// `fromKey` names an exact template port on the `from` end instead of
/// letting the allocator pick. It exists for ONE row — the ARC run — where
/// the whole point is WHICH port is used: a display's ARC-capable HDMI is a
/// `sink`, so the allocator's source-first preference would never choose it
/// and the fixture would claim a return-channel cycle it did not contain.
typedef _Run = ({String from, String to, int count, String? fromKey});

/// The wiring, as an integrator would describe it. The builder turns each
