// The 300-connection schematic fixture, and the code that generates it.
//
// M2's exit criterion (docs/09, docs/12 §5.1) asks the schematic to "route
// a 300-connection fixture within one frame at commit". A budget measured
// against a graph invented inside the test that measures it is a budget
// measured against nothing, so this fixture is a REAL `.rmpj` document,
// committed at
// `packages/rackpal_core/test/fixtures/e_three_hundred_links.rmpj.json`
// — the same treatment AC-052 gives the four starter projects, and the same
// CR-117 golden discipline `byte_roundtrip_test.dart` applies to them: the
// committed file is an INPUT, asserted, never regenerated by the run that
// reads it.
//
// WHY A FILE AND NOT A BUILDER CALL IN THE PERF TEST. Two reasons, and the
// second is the one that matters:
//   * the perf test then measures the same bytes on every machine and in
//     every future stage, including after a codec change nobody connected
//     to layout;
//   * building the document in-process would let a later change to this
//     builder quietly shrink the fixture — a 300-link budget met by a
//     280-link graph is not met. `schematic_perf_test.dart` reads the file
//     and counts its links before it times anything.
//
// ── WHAT IS IN IT ────────────────────────────────────────────────────────
// Real seed-catalog templates (`buildSeedCatalog`, AC-052 provenance), two
// racks, 109 devices and exactly 300 `Link`s (DR-121 took the keypads
// from 16 to 32, one bus cable each). It deliberately contains:
//   * A GENUINE CYCLE with a return channel — `AVR-1 → MTX-1 → DIS-2` and
//     `DIS-2 → AVR-1` on the display's ARC port (F01's second HDMI declares
//     `ReturnChannel.arc`, catalog_field.dart:59). Phase 0 has something to
//     break, and the bias has something to prefer.
//   * ZERO-PORT DEVICES — two `X01` blank panels and an `X03` shelf, which
//     get no symbol and must be counted rather than dropped.
//   * A SHELF CHAIN — the receiver and the set-top boxes sit on `SHF-1`, so
//     the sort key's rack resolution is a two-hop `hostRackOf` walk rather
//     than a single placement read.
//   * OFF-RACK DESTINATIONS — displays, speakers, keypads, cameras, which
//     phase 1 forces to the last layer.
//   * A STRUCTURE DEVICE at the left sheet edge (CR-072).
//
// ── WHAT IS DELIBERATELY NOT IN IT ───────────────────────────────────────
// `Service`s and `Net`s. The layout reads `Link.conductors` and nothing
// else, and one `Net` plus one `Service` per link would add roughly half
// again to a golden whose diff is supposed to be reviewable (CR-091's whole
// reason for plain JSON). This is a LAYOUT AND PERFORMANCE fixture and says
// so; the schedule's own fixture, when M2's schedule half needs one, is a
// different artifact with different contents.

import 'dart:convert';
import 'dart:io';

import 'package:rackpal_core/rackpal_core.dart';

/// Where the committed golden lives, relative to the package root.
const String kSchematicFixturePath =
    'test/fixtures/e_three_hundred_links.rmpj.json';

/// How many links the fixture is required to carry. The exit criterion's
/// own number, asserted rather than assumed — see the file header.
const int kSchematicFixtureLinkCount = 300;

const _codec = JsonDocumentCodec();

/// Reads the committed fixture off disk.
///
/// Throws rather than returning an `Outcome`: a perf test whose input did
/// not load has not measured a fast layout, it has measured nothing, and a
/// soft failure there would read as a pass.
RackDocument readSchematicFixture() {
  final file = File(kSchematicFixturePath);
  if (!file.existsSync()) {
    throw StateError(
      'the golden $kSchematicFixturePath is missing. It is a checked-in '
      'INPUT, not an output — regenerate deliberately with '
      'UPDATE_GOLDENS=1 and commit the diff.',
    );
  }
  final read = _codec.read(file.readAsBytesSync());
  if (read is! Ok<RackDocument>) {
    throw StateError('$kSchematicFixturePath did not decode: $read');
  }
  return read.value;
}

/// Encodes [doc] exactly as the golden is stored.
List<int> encodeFixture(RackDocument doc) => _codec.write(doc);

