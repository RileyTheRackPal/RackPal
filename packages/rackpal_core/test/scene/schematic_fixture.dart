/// One kind of device to place, and how many.
typedef _Roster = ({String catalogId, String prefix, int count});

/// The rail-mounted equipment. Ordered as it is racked, top of the list
/// first; `ruIndex` counts up from U1 as the list is walked, so the fixture
/// exercises the descending-`ruIndex` sort key rather than agreeing with it
/// by accident. Every entry has a real rail footprint in the seed catalog —
/// nothing here is rail-mounted that the catalog says cannot be.
const List<_Roster> _rackRoster = [
