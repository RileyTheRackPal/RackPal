      final result = migrateToCurrent(raw);

      expect(result, isA<Err<MigratedDoc>>());
      expect((result as Err<MigratedDoc>).error, isA<NotARackPalFileError>());
    });
  });

  group('A CHAIN THAT DID NOT ARRIVE IS AN ERROR, NOT A SUCCESS', () {
    // `migrateToCurrent`'s whole contract to the typed decoder downstream
    // is "whatever comes back is kSchemaVersion-shaped". A loop that
    // breaks out on a missing migration and still returns Ok breaks
    // exactly that contract, and `current` looks identical either way —
    // so nothing downstream can notice.

    test('a mangled "schemaVersion": -1 is REFUSED, not adopted as a '
        'healthy document', () {
      // Live today: -1 passes the minReaderVersion gate, finds no
      // migration, and would otherwise be decoded, adopted with
      // openReadOnly false, and written back out stamped -1.
      final raw = _v0Fixture()
        ..['schemaVersion'] = -1
        ..['minReaderVersion'] = -1;

      final result = migrateToCurrent(raw);

      expect(result, isA<Err<MigratedDoc>>());
      final error = (result as Err<MigratedDoc>).error;
      expect(error, isA<UnmigratableSchemaError>());
      final unmigratable = error as UnmigratableSchemaError;
      expect(unmigratable.storedSchemaVersion, -1);
      expect(unmigratable.stalledAtVersion, -1);
      expect(unmigratable.targetSchemaVersion, kSchemaVersion);
    });

    test('and it does NOT reach the typed decoder', () {
      const codec = JsonDocumentCodec();
      final raw = _v0Fixture()
        ..['schemaVersion'] = -1
        ..['minReaderVersion'] = -1;

      final result = codec.read(
        Uint8List.fromList(utf8.encode(jsonEncode(raw))),
      );

      expect(
        result,
        isA<Err<RackDocument>>(),
        reason:
            'an unmigrated envelope decoded by the typed decoder either '
            'throws a confusing "damaged file" or — if the shapes happen '
            'to overlap — loads partially, which is worse',
      );
      expect(
        (result as Err<RackDocument>).error,
        isA<UnmigratableSchemaError>(),
      );
    });

    test('EVERY version below kSchemaVersion has a migration — the '
        'append-only chain has no holes', () {
      // THE STANDING TRAP, checked mechanically rather than remembered: a
      // future kSchemaVersion bump that forgets its `migrations[]` entry.
      // Without this the omission does not fail loudly, it hands every
      // older file to the typed decoder unmigrated.
      for (var v = 0; v < kSchemaVersion; v++) {
        expect(
          migrations[v],
          isNotNull,
          reason:
              'migrations[$v] is missing, so every document stored at '
              'v$v stalls at $v instead of reaching v$kSchemaVersion',
        );
      }
    });

    test('a version at or above kSchemaVersion is NOT an unmigratable '
        'chain — the newer-file case still opens read-only', () {
      // Guards the guard: a post-loop check written as `version !=
      // kSchemaVersion` would refuse exactly the files §9.2 says to open.
      final raw = _v0Fixture()
        ..['schemaVersion'] = kSchemaVersion + 1
        ..['minReaderVersion'] = kMinReaderVersion;

      final result = migrateToCurrent(raw);

      expect(result, isA<Ok<MigratedDoc>>());
      expect((result as Ok<MigratedDoc>).openReadOnly, isTrue);
    });
  });

  group('CR-093 "never throws" covers ERRORS, not just EXCEPTIONS', () {
    // `on Exception catch` walks straight past every `Error`. On the read
    // path that means an unhandled future in whichever caller forgot to
    // await it — which reaches the user as Ctrl+O doing NOTHING AT ALL: no
    // dialog, no log, no crash, because nothing above installs a
    // zone/PlatformDispatcher handler.
    //
    // MEASURED, so this suite claims only what it reproduced: `jsonDecode`
    // is NOT the overflow risk json_limits.dart warns about. A probe
    // decoded 200 000 levels of nesting without incident — Dart's parser
    // keeps its own stack. The recursion that DOES overflow is
    // `deepSortKeys`/`JsonEncoder` on the WRITE side. So
    // `parseDocumentJsonTree`'s `on Object` clause is defensive breadth
    // with no reproduced case behind it and no test that mutating it
    // fails; that is recorded here rather than dressed up.
    //
    // `readFromJsonTree` is a different story: `asJsonMap` casts every key
    // with `k as String`, and a cast failure is a `TypeError`, an ERROR.
    // The shape below is exactly what a JSON tree assembled anywhere other
    // than `jsonDecode` can carry — a recovery sidecar, a future importer,
    // a test helper — and it reaches this function through the very split
    // that exists so a caller can parse somewhere else.
    test('a TypeError inside the typed decode comes back as an Err rather '
        'than escaping', () {
      final raw = <String, Object?>{
        'generator': 'RackPal',
        'schemaVersion': kSchemaVersion,
        'minReaderVersion': kMinReaderVersion,
        // A non-String key: `asJsonMap`'s `k as String` raises TypeError.
        'document': <Object?, Object?>{1: 'not a string key'},
      };

      // Proves the premise rather than assuming it: the thing being
      // caught really is an Error and really would slip past `on
      // Exception`.
      expect(
        () => asJsonMap(raw['document'], 'document'),
        throwsA(isA<Error>()),
      );

      final result = readFromJsonTree(raw);
      expect(
        result,
        isA<Err<RackDocument>>(),
        reason: 'an Error escaping here is an unhandled future upstream',
      );
      expect((result as Err<RackDocument>).error, isA<Error>());
    });
  });

  // ═══════════════════════════════════════════════════════════════════
  // v2 -> v3: `PortDef.position` becomes nullable (DR-105 §11.104.3/.4)
  // ═══════════════════════════════════════════════════════════════════
  group('v2 -> v3: the panel position that meant nothing', () {
    const codec = JsonDocumentCodec();
    const path = 'test/fixtures/v2_ports_with_positions.rmpj.json';

    Uint8List v2Bytes() => File(path).readAsBytesSync();

    RackDocument openV2() {
      final result = codec.read(v2Bytes());
      expect(
        result,
        isA<Ok<RackDocument>>(),
        reason: 'a v2 document must still open: ${result is Err ? result : ''}',
      );
      return (result as Ok<RackDocument>).value;
    }

    test('the fixture really is a v2 file carrying zero positions', () {
      // THE CONTROL. A migration fixture whose input does not contain the
      // thing being migrated proves the code compiles, not that it works,
      // and this corpus has a v1 sibling that exists for the same reason.
      final raw = jsonDecode(utf8.decode(v2Bytes())) as Map<String, Object?>;
      expect(raw['schemaVersion'], 2);
      expect(
        utf8.decode(v2Bytes()).split('"position"').length - 1,
        greaterThan(300),
        reason: '349 ports, every one of them at the origin',
      );
    });

    test('a real v2 file on disk still opens', () {
      expect(openV2().templates, isNotEmpty);
    });

    test('EVERY zero position becomes null, which means AUTO', () {
      // The whole of the migration. Read untouched, all 349 would mean
      // "manually placed at the origin" and the auto-layout would never
      // run for any template anybody had ever saved.
      final doc = openV2();
      final ports = [
        for (final snapshot in doc.templates.values) ...snapshot.body.ports,
      ];
      expect(ports, isNotEmpty, reason: 'the fixture has ports at all');
      expect(
        ports.where((p) => p.position != null),
        isEmpty,
        reason: 'a zero position is an UNPLACED port, not a placed one',
      );
    });

    test('it comes back stamped v3, so the next save is honestly labelled', () {
      final doc = openV2();
      expect(doc.schemaVersion, kSchemaVersion);
      expect(
        doc.minReaderVersion,
        kMinReaderVersion,
        reason:
            'this build re-saves it with `position` omitted; a stamp of 2 '
            'would promise a v2 reader it can open bytes whose absent '
            'key makes its `asJsonMap` throw',
      );
    });

    test('re-saving it round-trips byte-exactly from then on (CR-117)', () {
      // A MIGRATED file is not byte-equal to its INPUT, by definition.
      // What must hold is that the migrated form is stable: save it once
      // and every later load-and-save is a no-op.
      final once = codec.write(openV2());
      final twice = codec.write(
        (codec.read(once) as Ok<RackDocument>).value,
      );
      expect(utf8.decode(twice), utf8.decode(once));
    });

    test('a NON-zero position would survive, and one is proven to', () {
      // The half that makes the migration a rule rather than a delete.
      // Hand-built rather than taken from the corpus, because no producer
      // of a non-zero position existed at v2 and so no v2 file has one.
      final raw = jsonDecode(utf8.decode(v2Bytes())) as Map<String, Object?>;
      final templates =
          (raw['document']! as Map)['templates']! as Map<String, Object?>;
      final firstBody =
          (templates.values.first! as Map)['body']! as Map<String, Object?>;
      final ports = firstBody['ports']! as List;
      (ports.first! as Map)['position'] = <String, Object?>{
        'ruOffset': 1,
        'xTwelfth': 0,
        'xFineNm': 0,
        'yFineNm': 0,
      };
      final migrated = migrateV2ToV3(JsonMap.of(raw));
      final outPorts =
          ((((migrated['document']! as Map)['templates']! as Map).values.first!
                      as Map)['body']!
                  as Map)['ports']!
              as List;
      expect(
        (outPorts.first! as Map).containsKey('position'),
        isTrue,
        reason: 'a nudged port keeps its coordinate',
      );
    });

    test('a SheetItem position is a different type and is untouched', () {
      // `SheetItem.position` is `{gx, gy}` and shares only the key name.
      // The guard checks for exactly the four PanelPosition components,
      // which is why `c_fuller_project`'s sheet item survived the
      // regeneration with its position intact.
      final raw = <String, Object?>{
        'document': <String, Object?>{
          'sheets': <String, Object?>{
            's1': <String, Object?>{
              'items': <String, Object?>{
                'i1': <String, Object?>{
                  'position': <String, Object?>{'gx': 0, 'gy': 0},
                },
              },
            },
          },
        },
      };
      final migrated = migrateV2ToV3(JsonMap.of(raw));
      final item =
          ((((migrated['document']! as Map)['sheets']! as Map)['s1']!
                      as Map)['items']!
                  as Map)['i1']!
              as Map;
      expect(item.containsKey('position'), isTrue);
    });

    test('a malformed port is left exactly as it was', () {
      // A migration that threw on a bad port would turn a recoverable
      // file into an unopenable one; the decoder downstream reports the
      // real problem with the real key path.
      final raw = <String, Object?>{
        'document': <String, Object?>{
          'templates': <String, Object?>{
            't': <String, Object?>{
              'body': <String, Object?>{
                'ports': <Object?>[
                  'not a map',
                  <String, Object?>{'position': 'not a map either'},
                  <String, Object?>{
                    // Three of four components: malformed, not zero.
                    'position': <String, Object?>{
                      'ruOffset': 0,
                      'xTwelfth': 0,
                      'xFineNm': 0,
                    },
                  },
                ],
              },
            },
          },
        },
      };
      final migrated = migrateV2ToV3(JsonMap.of(raw));
      final ports =
          ((((migrated['document']! as Map)['templates']! as Map)['t']!
                      as Map)['body']!
                  as Map)['ports']!
              as List;
      expect(ports[0], 'not a map');
      expect((ports[1]! as Map)['position'], 'not a map either');
      expect(
        (ports[2]! as Map).containsKey('position'),
        isTrue,
        reason: 'a map missing yFineNm is not a zero position',
      );
    });
  });

  // ═══════════════════════════════════════════════════════════════════
  // v3 -> v4: `PortDef.carriedProtocols` is deleted (DR-134 §11.133)
  // ═══════════════════════════════════════════════════════════════════
  group('v3 -> v4: the field that was a second copy', () {
    const codec = JsonDocumentCodec();
    const path = 'test/fixtures/v3_carried_protocols.rmpj.json';

    Uint8List v3Bytes() => File(path).readAsBytesSync();

    RackDocument openV3() {
      final result = codec.read(v3Bytes());
      expect(
        result,
        isA<Ok<RackDocument>>(),
        reason: 'a v3 document must still open: ${result is Err ? result : ''}',
      );
      return (result as Ok<RackDocument>).value;
    }

    test('the fixture really is a v3 file carrying the key', () {
      // THE CONTROL, on its v1 and v2 siblings' precedent: a migration
      // fixture whose input does not contain the thing being migrated
      // proves the code compiles rather than that it works. This file is
      // the working `e_three_hundred_links` golden as it stood at v3,
      // copied before the regeneration that took it to v4, which is
      // exactly how `v2_ports_with_positions` came to exist.
      final raw = jsonDecode(utf8.decode(v3Bytes())) as Map<String, Object?>;
      expect(raw['schemaVersion'], 3);
      expect(
        utf8.decode(v3Bytes()).split('"carriedProtocols"').length - 1,
        greaterThan(300),
        reason: '348 ports, every one of them carrying an empty list',
      );
    });

    test('a real v3 file on disk still opens', () {
      expect(openV3().templates, isNotEmpty);
    });

    test('the key is gone from what this build writes back', () {
      // The whole of the migration, asserted on the ARTIFACT rather than
      // on the migration function: what matters is that the bytes this
      // build produces from a v3 file no longer carry the field.
      final out = utf8.decode(codec.write(openV3()));
      expect(out, isNot(contains('carriedProtocols')));
    });

    test('it comes back stamped CURRENT, and minReaderVersion STAYS at '
        '3', () {
      // THE DIVERGENCE IS THE POINT AND IT IS THE FIRST ONE. Every
      // earlier advance moved both stamps, because each made bytes an
      // older reader throws on. This one does not: a v3 reader meets the
      // absent key with `?? const <Object?>[]` and gets `[]`, which is
      // the only value the field ever held in any file. Raising the
      // stamp would refuse a file that opens perfectly (§11.133.5).
      final doc = openV3();
      // THE LITERAL `4` THAT USED TO BE HERE WAS RIGHT WHEN WRITTEN AND
      // WRONG NINE DAYS LATER. It read `expect(doc.schemaVersion, 4)`
      // beside the `kSchemaVersion` assertion, to pin the number as well
      // as the constant. But this case is about a v3 file reaching
      // CURRENT, not about reaching 4: v5 arrived, the chain grew a step,
      // and the literal failed while nothing it was guarding had changed.
      // `units_test.dart` is where a version literal belongs, because
      // there the whole point is that a bump is a deliberate edit with a
      // sentence attached. Here it was a second copy of a moving number.
      expect(doc.schemaVersion, kSchemaVersion);
      expect(doc.minReaderVersion, kMinReaderVersion);
      expect(doc.minReaderVersion, 3);
    });

    test('re-saving it round-trips byte-exactly from then on (CR-117)', () {
      final once = codec.write(openV3());
      final twice = codec.write((codec.read(once) as Ok<RackDocument>).value);
      expect(utf8.decode(twice), utf8.decode(once));
    });

    test('the older fixtures reach CURRENT through the whole chain', () {
      // v2 -> v3 -> v4 in one read, on a file that predates BOTH steps.
      // The v2 fixture carries 349 of the key as well as its 349 zero
      // positions, so it exercises this migration without being written
      // for it, which is what an append-only chain is supposed to buy.
      final result = codec.read(
        File(
          'test/fixtures/v2_ports_with_positions.rmpj.json',
        ).readAsBytesSync(),
      );
      expect(result, isA<Ok<RackDocument>>());
      final doc = (result as Ok<RackDocument>).value;
      // Current, not a literal: see the note two cases up.
      expect(doc.schemaVersion, kSchemaVersion);
      expect(
        utf8.decode(codec.write(doc)),
        isNot(contains('carriedProtocols')),
      );
    });

    test('a malformed port is left exactly as it was', () {
      // `migrateV2ToV3`'s sibling case, for the same reason: a migration
      // that threw on a bad port would turn a recoverable file into an
      // unopenable one.
      final raw = <String, Object?>{
        'document': <String, Object?>{
          'templates': <String, Object?>{
            't': <String, Object?>{
              'body': <String, Object?>{
                'ports': <Object?>[
                  'not a map',
                  <String, Object?>{'carriedProtocols': 'not a list'},
                ],
              },
            },
          },
        },
      };
      final migrated = migrateV3ToV4(JsonMap.of(raw));
      final ports =
          ((((migrated['document']! as Map)['templates']! as Map)['t']!
                      as Map)['body']!
                  as Map)['ports']!
              as List;
      expect(ports[0], 'not a map');
      expect(
        (ports[1]! as Map).containsKey('carriedProtocols'),
        isFalse,
        reason: 'the value is dropped whatever shape it was in',
      );
    });
  });

  // ═══════════════════════════════════════════════════════════════════
  // v4 -> v5: the plan model arrives and nothing in a v4 file changes
  // (DR-037, DR-136 §11.135.3)
  // ═══════════════════════════════════════════════════════════════════
  group('v4 -> v5: the advance that is not about bytes moving', () {
    const codec = JsonDocumentCodec();
    const path = 'test/fixtures/v4_before_plan.rmpj.json';

    Uint8List v4Bytes() => File(path).readAsBytesSync();

    RackDocument openV4() {
      final result = codec.read(v4Bytes());
      expect(
        result,
        isA<Ok<RackDocument>>(),
        reason: 'a v4 document must still open: ${result is Err ? result : ''}',
      );
      return (result as Ok<RackDocument>).value;
    }

    test('the fixture really is a v4 file with no plan data in it', () {
      // THE CONTROL, on its three siblings' precedent. This one is
      // shaped differently from theirs and the difference is the point:
      // v1, v2 and v3 assert that the fixture CONTAINS the thing being
      // migrated. There is nothing to contain here, so the control is
      // that it contains none of what v5 adds. A fixture that already
      // had an underlay would prove nothing about a v4 file.
      final raw = jsonDecode(utf8.decode(v4Bytes())) as Map<String, Object?>;
      expect(raw['schemaVersion'], 4);
      final document = raw['document']! as Map<String, Object?>;
      expect(document.containsKey('underlays'), isFalse);
      expect(utf8.decode(v4Bytes()), isNot(contains('planPin')));
      expect(utf8.decode(v4Bytes()), isNot(contains('riseAllowanceNm')));
      // And it is a real project rather than an empty one.
      expect((document['devices']! as Map).length, greaterThan(100));
    });

    test('a real v4 file on disk still opens', () {
      expect(openV4().devices, isNotEmpty);
      expect(openV4().underlays, isEmpty);
    });

    test('THE STEP MOVES NOTHING BUT THE STAMP', () {
      // The whole of DR-136 §11.135.3, as an artifact of the step itself.
      // This compared the v4 file with its re-encoding while v5 ended the
      // chain. DR-171's v6 strips the outlet keys this fixture carries, so
      // the claim is asserted where it lives: in `migrateV4ToV5`.
      final before = jsonDecode(utf8.decode(v4Bytes())) as _JsonMap;
      final after = migrateV4ToV5(
        jsonDecode(utf8.decode(v4Bytes())) as _JsonMap,
      );
      expect(after['schemaVersion'], 5);
      expect(jsonEncode({...after, 'schemaVersion': 4}), jsonEncode(before));
    });

    test('and it does NOT gain an underlays key, which is what keeps the '
        'line above true', () {
      expect(utf8.decode(codec.write(openV4())), isNot(contains('underlays')));
    });

    test('minReaderVersion stays 3, because a migrated v4 file has no '
        'plan data by construction', () {
      final doc = openV4();
      expect(doc.schemaVersion, kSchemaVersion);
      expect(doc.minReaderVersion, kMinReaderVersion);
      final raw =
          jsonDecode(utf8.decode(codec.write(doc))) as Map<String, Object?>;
      expect(raw['minReaderVersion'], 3);
    });
  });

  // ═══════════════════════════════════════════════════════════════════
  // v5 -> v6: the stored outlet counts leave the file (DR-171 §11.170.3)
  // ═══════════════════════════════════════════════════════════════════
  group('v5 -> v6: the outlet counts leave, and every hash that attested '
      'them moves with them', () {
    const codec = JsonDocumentCodec();
    // A v5 STARTER, copied before the regeneration that retired its keys.
    const path = 'test/fixtures/v5_outlet_counts.rmpj.json';

    Uint8List v5Bytes() => File(path).readAsBytesSync();
    _JsonMap v5Tree() => jsonDecode(utf8.decode(v5Bytes())) as _JsonMap;

    Map<String, _JsonMap> snapshotsOf(_JsonMap tree) {
      final document = tree['document']! as _JsonMap;
      return {
        for (final e in (document['templates']! as _JsonMap).entries)
          e.key: e.value! as _JsonMap,
      };
    }

    bool isRealHash(Object? h) =>
        h is String && RegExp(r'^sha256:[0-9a-f]{64}$').hasMatch(h);

    bool carriesKeys(_JsonMap snapshot) {
      final power = (snapshot['body']! as _JsonMap)['power']! as _JsonMap;
      return power.containsKey('outletsProvided') ||
          power.containsKey('outletsConsumed');
    }

    RackDocument openTree(_JsonMap tree) {
      final result = readFromJsonTree(tree);
      expect(result, isA<Ok<RackDocument>>(), reason: '$result');
      return (result as Ok<RackDocument>).value;
    }

    test('the fixture really is a v5 file whose real hashes attest bodies '
        'carrying the keys', () {
      // THE CONTROL. Without keys, or with placeholder hashes, this group
      // would prove that the strip compiles and nothing about the re-hash.
      final tree = v5Tree();
      expect(tree['schemaVersion'], 5);
      final attested = snapshotsOf(tree).values.where(
        (s) =>
            carriesKeys(s) &&
            isRealHash(s['contentHash']) &&
            s['contentHash'] == canonicalBodyHash(s['body']! as _JsonMap),
      );
      expect(attested, isNotEmpty);
    });

    test('it opens, and nothing it writes carries either key', () {
      // THE QUOTED KEY, NOT THE WORD. The stored `N01` snapshot still
      // describes itself as "two inlets means outletsConsumed: 2", and a
      // snapshot is a record of the template as it was placed, which no
      // migration rewrites. The first draft of this case asserted the word
      // and failed on that prose while every key was gone.
      final written = utf8.decode(codec.write(openTree(v5Tree())));
      expect(written, isNot(contains('"outletsProvided"')));
      expect(written, isNot(contains('"outletsConsumed"')));
      expect(
        (jsonDecode(written) as _JsonMap)['schemaVersion'],
        kSchemaVersion,
      );
    });

    test('EVERY HASH THAT ATTESTED ITS BODY STILL DOES, re-taken over the '
        'stripped body', () {
      // The migration hashes the raw stripped map; verification hashes the
      // decoded body through `templateBodyToJson`. This is the assertion
      // that the two agree on a real file rather than in an argument.
      final before = snapshotsOf(v5Tree());
      final doc = openTree(v5Tree());
      var checked = 0;
      for (final entry in before.entries) {
        final hash = entry.value['contentHash'];
        final body = entry.value['body']! as _JsonMap;
        if (!carriesKeys(entry.value) || !isRealHash(hash)) continue;
        if (hash != canonicalBodyHash(body)) continue;
        final migrated = doc.templates[entry.key]!;
        expect(migrated.contentHash, isNot(hash), reason: entry.key);
        expect(
          templateHashMatches(migrated.body, migrated.contentHash),
          isTrue,
          reason: entry.key,
        );
        checked++;
      }
      expect(checked, greaterThan(0));
    });

    test('a device that named its snapshot by hash still does', () {
      final tree = v5Tree();
      final snapshots = snapshotsOf(tree);
      final devices = (tree['document']! as _JsonMap)['devices']! as _JsonMap;
      final matchedBefore = <String>[];
      for (final e in devices.entries) {
        final ref = (e.value! as _JsonMap)['templateRef']! as _JsonMap;
        final snapshot = snapshots['${ref['templateId']}@${ref['version']}'];
        if (snapshot == null || !carriesKeys(snapshot)) continue;
        if (isRealHash(ref['contentHash']) &&
            ref['contentHash'] == snapshot['contentHash']) {
          matchedBefore.add(e.key);
        }
      }
      expect(matchedBefore, isNotEmpty);

      final doc = openTree(v5Tree());
      for (final id in matchedBefore) {
        final device = doc.devices[Uuid(id)]!;
        final snapshot = doc.templates[templateKeyFor(device.templateRef)]!;
        expect(
          device.templateRef.contentHash,
          snapshot.contentHash,
          reason: device.designator,
        );
      }
    });

    test('A BODY EDITED OUTSIDE THE PRODUCT STILL READS AS EDITED', () {
      // The half that makes the re-hash safe: a hash that did not attest
      // its body is carried, never refreshed into agreement with it.
      final tree = v5Tree();
      final entry = snapshotsOf(tree).entries.firstWhere(
        (e) => carriesKeys(e.value) && isRealHash(e.value['contentHash']),
      );
      final stale = entry.value['contentHash'];
      (entry.value['body']! as _JsonMap)['displayName'] = 'Edited by hand';

      final migrated = openTree(tree).templates[entry.key]!;
      expect(migrated.contentHash, stale);
      expect(templateHashMatches(migrated.body, migrated.contentHash), isFalse);
    });

    test(
      'minReaderVersion does not move, because a v5 reader loses nothing',
      () {
        final written =
            jsonDecode(utf8.decode(codec.write(openTree(v5Tree()))))
                as _JsonMap;
        expect(written['minReaderVersion'], v5Tree()['minReaderVersion']);
      },
    );

    test('the step alone re-stamps a tree with nothing to strip', () {
      final migrated = migrateV5ToV6({'schemaVersion': 5, 'keep': 'me'});
      expect(migrated['schemaVersion'], 6);
      expect(migrated['keep'], 'me');
    });
  });
