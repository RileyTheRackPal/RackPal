// The migration corpus (docs/03-architecture.md §9.2, CR-093, CR-094).
//
// v0 -> v1 is this milestone's own exit criterion ("one v0->v1 migration
// fixture in the golden corpus"). v0 called the root envelope's `sequence`
// counter `revision` instead (the synthetic reenactment of CR-094's real,
// documented rename); `migrateV0ToV1` renames the key and bumps
// `schemaVersion`. Also covers the `minReaderVersion > kSchemaVersion`
// refusal case.
//
// v1 -> v2 is the first REAL one, and its fixture is a real FILE on disk
// (`test/fixtures/v1_templates_and_power.rmpj.json`) rather than a map
// built in this file: v1 shipped, so proving "a v1 document still opens"
// means opening v1 BYTES. The file is an input golden — checked in, never
// regenerated by a test — and it carries the one thing v2 changed, a
// `PowerProfile` whose outlet counts v1 always wrote explicitly and v2 may
// omit.
