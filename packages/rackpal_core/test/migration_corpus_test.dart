  group('v1 -> v2: the outlet-count omission (CR-114, CR-117)', () {
    const codec = JsonDocumentCodec();
    const path = 'test/fixtures/v1_templates_and_power.rmpj.json';

    Uint8List v1Bytes() => File(path).readAsBytesSync();

    RackDocument openV1() {
      final result = codec.read(v1Bytes());
      expect(
        result,
        isA<Ok<RackDocument>>(),
        reason: 'a v1 document must still open: ${result is Err ? result : ''}',
      );
      return (result as Ok<RackDocument>).value;
    }

    test('a real v1 file on disk still opens', () {
      final doc = openV1();

      expect(doc.info.projectName, 'V1 Power Fixture');
      expect(doc.racks, hasLength(1));
      expect(doc.devices, hasLength(2));
      expect(doc.templates, hasLength(3));
    });

    test('it comes back stamped v2, so the next save is honestly labelled', () {
      final doc = openV1();

      expect(doc.schemaVersion, kSchemaVersion);
      expect(
        doc.minReaderVersion,
        kMinReaderVersion,
        reason:
            'this build will re-save it in v2 form, with outlet keys '
            'omitted; a stamp of 1 would promise a v1 reader it can open '
            'bytes that make it throw',
      );
    });

    test("v1's explicit counts pass v1 -> v2 untouched, and v5 -> v6 is "
        'the step that removes them (DR-171)', () {
      // Until DR-171 this case asserted that every count survived the WHOLE
      // chain exactly, v1's zeros included, because the fields existed. The
      // v1 -> v2 half is still true and still asserted: that step does not
      // reinterpret a zero. The chain as a whole now ends with no count at
      // all, because no template stores one.
      final raw = jsonDecode(utf8.decode(v1Bytes())) as _JsonMap;
      final v2 = migrateV1ToV2(raw);
      final templates = (v2['document']! as _JsonMap)['templates']! as _JsonMap;
      final amp =
          (templates['tpl.demo.amp@1']! as _JsonMap)['body']! as _JsonMap;
      expect((amp['power']! as _JsonMap)['outletsProvided'], 0);

      final written = utf8.decode(codec.write(openV1()));
      expect(written, isNot(contains('"outletsProvided"')));
      expect(written, isNot(contains('"outletsConsumed"')));
    });

    test('re-saving a migrated v1 document writes v2 bytes that '
        'round-trip', () {
      final doc = openV1();
      final bytes = codec.write(doc);
      final root = jsonDecode(utf8.decode(bytes)) as Map<String, Object?>;

      expect(root['schemaVersion'], kSchemaVersion);
      expect(root['minReaderVersion'], kMinReaderVersion);

      // CR-117 still holds across the version boundary.
      final reread = codec.read(bytes);
      expect(reread, isA<Ok<RackDocument>>());
      expect(codec.write((reread as Ok<RackDocument>).value), equals(bytes));
    });

    test('migrateV1ToV2 raises minReaderVersion and never lowers it', () {
      final raised = migrateV1ToV2({
        'schemaVersion': 1,
        'minReaderVersion': 1,
        'keep': 'me',
