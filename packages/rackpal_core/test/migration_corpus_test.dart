/// A v0 file: `schemaVersion: 0`, and the root envelope's sync-cursor
/// counter spelled `"revision"` rather than v1's `"sequence"` (CR-094).
_JsonMap _v0Fixture() => {
  'generator': 'RackPal',
  'id': 'v0-migration-fixture',
  'appVersion': '0.0.9',
  'createdAt': '2025-01-01T00:00:00.000000Z',
  'modifiedAt': '2025-01-01T00:00:00.000000Z',
  'schemaVersion': 0,
  'minReaderVersion': 0,
  'revision': 5,
  'document': _minimalDocumentBody(),
};

void main() {
  group('v0 -> v1 migration fixture (CR-093, CR-094)', () {
    test('migrateToCurrent renames "revision" to "sequence"', () {
      final result = migrateToCurrent(_v0Fixture());

      expect(result, isA<Ok<MigratedDoc>>());
      final migrated = (result as Ok<MigratedDoc>).value;

      expect(migrated.raw['sequence'], 5);
      expect(migrated.raw.containsKey('revision'), isFalse);
      expect(migrated.raw['schemaVersion'], kSchemaVersion);
      expect(result.openReadOnly, isFalse);
    });

    test('end-to-end: JsonDocumentCodec.read opens a real v0 file', () {
      const jsonCodec = JsonDocumentCodec();
      final v0Bytes = Uint8List.fromList(utf8.encode(jsonEncode(_v0Fixture())));

      final result = jsonCodec.read(v0Bytes);

      expect(result, isA<Ok<RackDocument>>());
      final doc = (result as Ok<RackDocument>).value;
      expect(doc.sequence, 5);
      expect(doc.schemaVersion, kSchemaVersion);
      expect(doc.info.projectName, 'V0 Fixture');
    });
  });

  group('v1 -> v2: the outlet-count omission (CR-114, CR-117)', () {
    const codec = JsonDocumentCodec();
    const path = 'test/fixtures/v1_templates_and_power.rmpj.json';

    Uint8List v1Bytes() => File(path).readAsBytesSync();

    RackDocument openV1() {
      final result = codec.read(v1Bytes());
      expect(
        result,
        isA<Ok<RackDocument>>(),
        reason: 'a v1 document must still open: ${result is Err ? result : ''}',
      );
      return (result as Ok<RackDocument>).value;
    }

    test('a real v1 file on disk still opens', () {
      final doc = openV1();

      expect(doc.info.projectName, 'V1 Power Fixture');
      expect(doc.racks, hasLength(1));
      expect(doc.devices, hasLength(2));
      expect(doc.templates, hasLength(3));
    });

    test('it comes back stamped v2, so the next save is honestly labelled', () {
      final doc = openV1();

      expect(doc.schemaVersion, kSchemaVersion);
      expect(
        doc.minReaderVersion,
        kMinReaderVersion,
        reason:
            'this build will re-save it in v2 form, with outlet keys '
            'omitted; a stamp of 1 would promise a v1 reader it can open '
            'bytes that make it throw',
      );
    });

    test('every outlet count survives the migration EXACTLY — v1 zeros are '
        'not reinterpreted', () {
      // The migration deliberately does not translate v1's explicit `0`
      // into v2's absent key. v1's own catalogs authored `outletsProvided:
      // 0` on most entries as a real measurement (an amplifier provides no
      // outlets), and the file records no way to tell those from the old
      // non-nullable default. Rewriting them would destroy true
      // measurements to recover a minority of fabricated ones, and
      // "this was never authored" is as much a guess as "this was
      // measured" (G4). See `migrateV1ToV2`.
      final doc = openV1();
      PowerProfile power(String key) => doc.templates[key]!.body.power;

      expect(power('tpl.demo.pdu@1').outletsProvided, 16);
      expect(power('tpl.demo.pdu@1').outletsConsumed, 1);
      expect(power('tpl.demo.amp@1').outletsProvided, 0);
      expect(power('tpl.demo.amp@1').outletsConsumed, 1);
      expect(power('tpl.demo.blank@1').outletsProvided, 0);
      expect(power('tpl.demo.blank@1').outletsConsumed, 0);
      for (final key in doc.templates.keys) {
        expect(
          power(key).outletsProvided,
          isNotNull,
          reason: '$key stated a count in v1; migrating must not erase it',
        );
      }
    });

    test('re-saving a migrated v1 document writes v2 bytes that '
        'round-trip', () {
      final doc = openV1();
      final bytes = codec.write(doc);
      final root = jsonDecode(utf8.decode(bytes)) as Map<String, Object?>;

      expect(root['schemaVersion'], kSchemaVersion);
      expect(root['minReaderVersion'], kMinReaderVersion);

      // CR-117 still holds across the version boundary.
      final reread = codec.read(bytes);
      expect(reread, isA<Ok<RackDocument>>());
      expect(codec.write((reread as Ok<RackDocument>).value), equals(bytes));
    });

    test('migrateV1ToV2 raises minReaderVersion and never lowers it', () {
      final raised = migrateV1ToV2({
        'schemaVersion': 1,
        'minReaderVersion': 1,
        'keep': 'me',
      });
      expect(raised['schemaVersion'], 2);
      expect(raised['minReaderVersion'], kMinReaderVersion);
      expect(raised['keep'], 'me', reason: 'the payload is passed through');

      final alreadyStricter = migrateV1ToV2({
        'schemaVersion': 1,
        'minReaderVersion': 7,
      });
      expect(alreadyStricter['minReaderVersion'], 7);
    });

    test('the chain runs BOTH migrations for a v0 file', () {
      final result = migrateToCurrent(_v0Fixture());

      expect(result, isA<Ok<MigratedDoc>>());
      final raw = (result as Ok<MigratedDoc>).value.raw;
      expect(raw['schemaVersion'], 2, reason: 'v0 -> v1 -> v2');
      expect(raw['sequence'], 5, reason: 'v0 -> v1 still ran');
      expect(
        raw['minReaderVersion'],
        kMinReaderVersion,
        reason: 'v1 -> v2 still ran',
      );
    });
  });

  group('minReaderVersion newer than this build refuses (CR-093)', () {
    test('produces Err(NewerSchemaError) rather than opening', () {
      final raw = _v0Fixture()
        ..['minReaderVersion'] = 999
        ..['schemaVersion'] = 999;

      final result = migrateToCurrent(raw);

      expect(result, isA<Err<MigratedDoc>>());
      expect((result as Err<MigratedDoc>).error, isA<NewerSchemaError>());
    });
  });

  group('generator mismatch (CR-092)', () {
    test('produces Err(NotARackPalFileError)', () {
      final raw = _v0Fixture()..['generator'] = 'SomeOtherApp';

      final result = migrateToCurrent(raw);

      expect(result, isA<Err<MigratedDoc>>());
      expect((result as Err<MigratedDoc>).error, isA<NotARackPalFileError>());
    });
  });

  group('A CHAIN THAT DID NOT ARRIVE IS AN ERROR, NOT A SUCCESS', () {
    // `migrateToCurrent`'s whole contract to the typed decoder downstream
    // is "whatever comes back is kSchemaVersion-shaped". A loop that
    // breaks out on a missing migration and still returns Ok breaks
    // exactly that contract, and `current` looks identical either way —
    // so nothing downstream can notice.

    test('a mangled "schemaVersion": -1 is REFUSED, not adopted as a '
        'healthy document', () {
      // Live today: -1 passes the minReaderVersion gate, finds no
      // migration, and would otherwise be decoded, adopted with
      // openReadOnly false, and written back out stamped -1.
      final raw = _v0Fixture()
        ..['schemaVersion'] = -1
        ..['minReaderVersion'] = -1;

      final result = migrateToCurrent(raw);

      expect(result, isA<Err<MigratedDoc>>());
      final error = (result as Err<MigratedDoc>).error;
      expect(error, isA<UnmigratableSchemaError>());
      final unmigratable = error as UnmigratableSchemaError;
      expect(unmigratable.storedSchemaVersion, -1);
      expect(unmigratable.stalledAtVersion, -1);
      expect(unmigratable.targetSchemaVersion, kSchemaVersion);
    });

    test('and it does NOT reach the typed decoder', () {
      const codec = JsonDocumentCodec();
      final raw = _v0Fixture()
        ..['schemaVersion'] = -1
        ..['minReaderVersion'] = -1;

      final result = codec.read(
        Uint8List.fromList(utf8.encode(jsonEncode(raw))),
      );

      expect(
        result,
        isA<Err<RackDocument>>(),
        reason:
            'an unmigrated envelope decoded by the typed decoder either '
            'throws a confusing "damaged file" or — if the shapes happen '
            'to overlap — loads partially, which is worse',
      );
      expect(
        (result as Err<RackDocument>).error,
        isA<UnmigratableSchemaError>(),
      );
    });

    test('EVERY version below kSchemaVersion has a migration — the '
        'append-only chain has no holes', () {
      // THE STANDING TRAP, checked mechanically rather than remembered: a
      // future kSchemaVersion bump that forgets its `migrations[]` entry.
      // Without this the omission does not fail loudly, it hands every
      // older file to the typed decoder unmigrated.
      for (var v = 0; v < kSchemaVersion; v++) {
        expect(
          migrations[v],
          isNotNull,
          reason:
              'migrations[$v] is missing, so every document stored at '
              'v$v stalls at $v instead of reaching v$kSchemaVersion',
        );
      }
    });

    test('a version at or above kSchemaVersion is NOT an unmigratable '
        'chain — the newer-file case still opens read-only', () {
      // Guards the guard: a post-loop check written as `version !=
      // kSchemaVersion` would refuse exactly the files §9.2 says to open.
      final raw = _v0Fixture()
        ..['schemaVersion'] = kSchemaVersion + 1
        ..['minReaderVersion'] = kMinReaderVersion;

      final result = migrateToCurrent(raw);

      expect(result, isA<Ok<MigratedDoc>>());
      expect((result as Ok<MigratedDoc>).openReadOnly, isTrue);
    });
  });

  group('CR-093 "never throws" covers ERRORS, not just EXCEPTIONS', () {
    // `on Exception catch` walks straight past every `Error`. On the read
    // path that means an unhandled future in whichever caller forgot to
    // await it — which reaches the user as Ctrl+O doing NOTHING AT ALL: no
    // dialog, no log, no crash, because nothing above installs a
    // zone/PlatformDispatcher handler.
    //
    // MEASURED, so this suite claims only what it reproduced: `jsonDecode`
    // is NOT the overflow risk json_limits.dart warns about. A probe
    // decoded 200 000 levels of nesting without incident — Dart's parser
    // keeps its own stack. The recursion that DOES overflow is
    // `deepSortKeys`/`JsonEncoder` on the WRITE side. So
    // `parseDocumentJsonTree`'s `on Object` clause is defensive breadth
    // with no reproduced case behind it and no test that mutating it
    // fails; that is recorded here rather than dressed up.
    //
    // `readFromJsonTree` is a different story: `asJsonMap` casts every key
    // with `k as String`, and a cast failure is a `TypeError`, an ERROR.
    // The shape below is exactly what a JSON tree assembled anywhere other
    // than `jsonDecode` can carry — a recovery sidecar, a future importer,
    // a test helper — and it reaches this function through the very split
    // that exists so a caller can parse somewhere else.
    test('a TypeError inside the typed decode comes back as an Err rather '
        'than escaping', () {
      final raw = <String, Object?>{
        'generator': 'RackPal',
        'schemaVersion': kSchemaVersion,
        'minReaderVersion': kMinReaderVersion,
        // A non-String key: `asJsonMap`'s `k as String` raises TypeError.
        'document': <Object?, Object?>{1: 'not a string key'},
      };

      // Proves the premise rather than assuming it: the thing being
      // caught really is an Error and really would slip past `on
      // Exception`.
      expect(
        () => asJsonMap(raw['document'], 'document'),
        throwsA(isA<Error>()),
      );

      final result = readFromJsonTree(raw);
      expect(
        result,
        isA<Err<RackDocument>>(),
        reason: 'an Error escaping here is an unhandled future upstream',
      );
      expect((result as Err<RackDocument>).error, isA<Error>());
    });
  });
}
